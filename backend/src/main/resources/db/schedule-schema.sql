CREATE TABLE IF NOT EXISTS scheduled_flights
(
    id                              VARCHAR PRIMARY KEY,
    flight_name                     VARCHAR NOT NULL,
    flight_number                   BIGINT,
    main_flight                     VARCHAR,
    flight_direction                VARCHAR NOT NULL,
    prefix_iata                     VARCHAR,
    prefix_icao                     VARCHAR,
    airline_code                    BIGINT,
    is_operational_flight           BOOLEAN NOT NULL DEFAULT TRUE,
    service_type                    VARCHAR,
    origin_code                     VARCHAR,
    destination_code                VARCHAR,
    route_destinations              VARCHAR[],
    route_eu                        VARCHAR,
    route_visa                      BOOLEAN,
    aircraft_registration           VARCHAR,
    aircraft_iata_main              VARCHAR,
    aircraft_iata_sub               VARCHAR,
    schedule_date                   DATE,
    schedule_time                   VARCHAR,
    schedule_date_time              TIMESTAMPTZ,
    estimated_landing_time          TIMESTAMPTZ,
    actual_landing_time             TIMESTAMPTZ,
    public_estimated_off_block_time TIMESTAMPTZ,
    actual_off_block_time           TIMESTAMPTZ,
    expected_time_gate_open         TIMESTAMPTZ,
    expected_time_boarding          TIMESTAMPTZ,
    expected_time_gate_closing      TIMESTAMPTZ,
    expected_time_on_belt           TIMESTAMPTZ,
    expected_security_filter        VARCHAR,
    last_updated_at                 TIMESTAMPTZ,
    terminal                        BIGINT,
    pier                            VARCHAR,
    gate                            VARCHAR,
    flight_states                   VARCHAR[],
    codeshares                      VARCHAR[],
    baggage_belts                   VARCHAR[],
    transfer_positions              BIGINT[],
    checkin_rows                    VARCHAR[],
    checkin_start_time              TIMESTAMPTZ,
    checkin_end_time                TIMESTAMPTZ,
    checkin_allocations             JSON
);
